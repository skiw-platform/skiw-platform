"""Every context that imports Django settings carries the session lifetime and interim auth
variables with a valid value (plan M2b "Wiring", M3b; UNI-16). A missing one is a start-up
failure, so each context is checked here and then started. Rendered host Compose:
infra/host/tests/test_compose_config.py."""

import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from tests.settings_env import REQUIRED

REPO = Path(__file__).resolve().parents[2]
VALUES = REQUIRED  # spec §8.1 (session), T5, Flow 5.1, T18 (auth; owner Q6 (a))
NAMES = tuple(VALUES)
# generated by `make .env`, never committed; web and worker read all three (token key: M4c-4b)
KEYS = ("TENANT_SOURCE_KEY", "LOGIN_BLOB_KEY", "TENANT_TOKEN_KEY")


def assignments(text: str, pattern: str) -> dict[str, str]:
    return {name: value for name, value in re.findall(pattern, text) if name in NAMES}


def env_file(path: str) -> dict[str, str]:
    return assignments((REPO / path).read_text(), r"(?m)^([A-Z0-9_]+)=(.*)$")


def tool_env() -> dict[str, str]:
    makefile = (REPO / "Makefile").read_text().replace("\\\n", " ")
    line = re.search(r"(?m)^TOOL_ENV := (.*)$", makefile)
    assert line is not None
    return assignments(line[1], r"([A-Z0-9_]+)=(\S+)")


def block(text: str, start: str, end: str) -> str:
    match = re.search(rf"(?ms)^{start}$(.*?)(?=^{end})", text)
    assert match is not None, start
    return match[1]


def label_step() -> dict[str, str]:
    ci = (REPO / ".github" / "workflows" / "ci.yml").read_text()
    step = block(ci, r"      - name: Label image[^\n]*", r"      - ")
    for name in NAMES:
        assert f"-e {name} " in step or f"-e {name}\n" in step  # passed into the container
    return assignments(step, r'(?m)^ {10}([A-Z0-9_]+): "?([^"\n]*)"?$')


CONTEXTS = {
    "env/staging.env": lambda: env_file("infra/host/env/staging.env"),
    "env/production.env": lambda: env_file("infra/host/env/production.env"),
    "env/ci.env": lambda: env_file("infra/host/env/ci.env"),
    ".env.example": lambda: env_file(".env.example"),
    "Makefile TOOL_ENV": tool_env,
    "CI label step": label_step,
}


@pytest.mark.parametrize("context", CONTEXTS)
def test_context_carries_every_value(context: str) -> None:
    assert CONTEXTS[context]() == VALUES


@pytest.mark.parametrize("service", ["app", "worker"])
def test_local_compose_service_takes_every_value_from_the_env_file(service: str) -> None:
    compose = (REPO / "docker-compose.yml").read_text()
    environment = block(compose, f"  {service}:", r"  [a-z]+:|volumes:")
    for name in NAMES:
        assert f"      {name}: ${{{name}:?set in .env}}\n" in environment


@pytest.mark.parametrize("context", CONTEXTS)
def test_context_values_start_the_settings(context: str) -> None:
    result = subprocess.run(
        [sys.executable, "-c", "import config.settings"],
        env={
            "PATH": os.environ["PATH"],
            "PYTHONPATH": str(REPO / "app"),
            "DJANGO_SECRET_KEY": "test-only-not-a-secret",
            "DATABASE_URL": "postgres://u:p@localhost:5432/db",
            **CONTEXTS[context](),
        },
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr[-2000:]


@pytest.mark.parametrize("service", ["app", "worker"])
@pytest.mark.parametrize("key", KEYS)
def test_local_compose_service_takes_each_app_key_from_the_env_file(service: str, key: str) -> None:
    compose = (REPO / "docker-compose.yml").read_text()
    environment = block(compose, f"  {service}:", r"  [a-z]+:|volumes:")
    assert f"      {key}: ${{{key}:?set in .env}}\n" in environment


@pytest.mark.parametrize("key", KEYS)
def test_each_local_app_key_is_generated_never_committed(key: str) -> None:
    """Plans M2c, M3b: no key value in .env.example (UNI-07); `make .env` appends a random v1
    line."""
    assert not re.search(rf"(?m)^{key}", (REPO / ".env.example").read_text())
    rule = block((REPO / "Makefile").read_text(), r"\.env:", r"\S")
    assert f"printf '{key}=v1:%s\\n' \"$$(openssl rand -base64 32)\" >> .env" in rule


def test_local_web_takes_the_passkey_relying_party_from_the_env_file() -> None:
    """Plan M3g: web checks both at start-up; the worker never runs a ceremony. Hosts derive them
    from SKIW_HOSTNAME (infra/host/tests/test_compose_config.py)."""
    names = ("SKIW_WEBAUTHN_RP_ID", "SKIW_WEBAUTHN_ORIGIN")
    example = dict(
        re.findall(r"(?m)^(SKIW_WEBAUTHN_[A-Z_]+)=(.*)$", (REPO / ".env.example").read_text())
    )
    assert example == {
        "SKIW_WEBAUTHN_RP_ID": "localhost",
        "SKIW_WEBAUTHN_ORIGIN": "http://localhost:8000",
    }
    compose = (REPO / "docker-compose.yml").read_text()
    for name in names:
        assert f"      {name}: ${{{name}:?set in .env}}\n" in block(
            compose, "  app:", r"  [a-z]+:|volumes:"
        )
        assert name not in block(compose, "  worker:", r"  [a-z]+:|volumes:")
